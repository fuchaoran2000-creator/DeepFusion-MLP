#!/usr/bin/python3
"""Verify saved real ROS inputs against training features and batch correction.

Do not compare different SLAM executions for numerical equivalence. This tool
reuses each run's captured inputs and verifies the model publisher from that run.
"""
import argparse
import hashlib
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import numpy as np
import torch
from causal_stream import extract, ResidualStream, PROTOCOL, world, wrap
from mentor_benchmark import load_sequence, features, corrected, predict, metrics, load_pose
from residual_models import Regressor


def verify(row, checkpoint=None, publication=None, portable=None):
    torch.set_num_threads(1)
    path=Path(row['sampled_stream'])
    with np.load(path,allow_pickle=False) as source:
        data={k:source[k].copy() for k in source.files}
    seq=load_sequence(row,float(data['hz']))
    report={'sequence':seq.name,'samples':len(seq.t),'protocol':PROTOCOL,
            'stream_sha256':hashlib.sha256(path.read_bytes()).hexdigest(),
            'input_available_fraction':float(data['available'].mean()),
            'ready_fraction':float(data['ready'].mean()),
            'reference_used_to_define_inputs':False,'raw_metrics':metrics(seq,seq.cart)}
    source_config=str(data['config'])
    _,_,x,ready,_=extract(data['t'],data['cart'],data['odom'],data['available'],source_config)
    np.testing.assert_array_equal(x,data['features'])
    np.testing.assert_array_equal(ready,data['ready'])
    np.testing.assert_allclose(features(seq,source_config),x[1:],atol=1e-7,rtol=1e-7)
    report['captured_feature_max_error']=float(np.abs(x-data['features']).max())
    report['training_feature_max_error']=float(np.abs(features(seq,source_config)-x[1:]).max())
    # Grid timestamps were generated by integer indexing, no accumulated float dt.
    np.testing.assert_array_equal(data['t'],data['t'][0]+np.arange(len(data['t']))/float(data['hz']))
    usable=data['available']
    assert ((data['cart_source_t'][usable]<=data['t'][usable]) &
            (data['odom_source_t'][usable]<=data['t'][usable])).all()
    assert (data['t'][usable]-data['cart_source_t'][usable]<=.15).all()
    assert (data['t'][usable]-data['odom_source_t'][usable]<=.15).all()
    if checkpoint:
        state=torch.load(checkpoint,map_location='cpu',weights_only=False)
        assert state['stream_protocol']==PROTOCOL
        model=Regressor(len(state['norm']['xm']),'mlp',state['uncertainty'])
        model.load_state_dict(state['model_state_dict']);model.eval()
        norm={k:v.numpy() for k,v in state['norm'].items()}
        def forward(z):
            with torch.inference_mode():return model(torch.from_numpy(z[None])).numpy()[0]
        engine=ResidualStream(state['config'],state['target'],norm,forward,state['alpha'],state['gate_parameters'],state.get('integration_tau_s'))
        poses=[];statuses=[]
        for t,c,o,a in zip(data['t'],data['cart'],data['odom'],data['available']):
            pose,status=engine.step(t,c,o,a);poses.append(pose);statuses.append(status)
        poses=np.array(poses);fallback=np.array([s['fallback'] for s in statuses])
        mean,sigma,z=predict(model,norm,seq,state['config'])
        gate=state['gate_parameters']
        mask=np.ones(len(mean),bool) if gate is None else (
            ((sigma/norm['ys']).mean(1)<=gate['sigma_threshold']) & (np.abs(z).max(1)<=gate['ood_threshold']))
        mask &= seq.ready[1:]
        alpha=state['alpha'] if gate is None else gate['gate_alpha']
        batch=corrected(seq,mean,alpha,state['target'],mask,state.get('integration_tau_s'))
        batch_world=np.array([world(p,engine.features.origin_cart) for p in batch])
        batch_fallback=np.r_[True,(~mask)|(alpha==0)]
        batch_world[batch_fallback]=data['cart'][batch_fallback]
        np.testing.assert_array_equal(batch_fallback,fallback)
        np.testing.assert_allclose(batch_world,poses,atol=3e-5,rtol=0)
        np.testing.assert_array_equal(poses[fallback],data['cart'][fallback])
        report.update(checkpoint=str(Path(checkpoint).resolve()),
            checkpoint_sha256=hashlib.sha256(Path(checkpoint).read_bytes()).hexdigest(),
            batch_vs_step_max_error=float(np.abs(batch_world-poses).max()),
            fallback_fraction=float(fallback.mean()),corrected_metrics=metrics(seq,batch))
        if portable:
            from portable_residual import PortableResidual
            numpy_model=PortableResidual(portable);numpy_poses=[];numpy_fallback=[]
            for t,c,o,a in zip(data['t'],data['cart'],data['odom'],data['available']):
                p,s=numpy_model.step(t,c,o,bool(a));numpy_poses.append(p);numpy_fallback.append(s['fallback'])
            numpy_poses=np.array(numpy_poses)
            np.testing.assert_array_equal(numpy_fallback,fallback)
            np.testing.assert_allclose(numpy_poses,poses,atol=3e-5,rtol=0)
            report['portable_vs_torch_max_error']=float(np.abs(numpy_poses-poses).max())
        if state['config']==source_config and bool(data.get('has_model',False)):
            np.testing.assert_array_equal(fallback,data['fallback'])
            np.testing.assert_allclose(poses,data['output'],atol=1e-10,rtol=0)
            report['saved_live_vs_step_max_error']=float(np.abs(poses-data['output']).max())
            if publication:
                pt,pp=load_pose(publication)
                np.testing.assert_allclose(pt,data['t'],atol=1e-8,rtol=0)
                error=pp-poses;error[:,2]=wrap(error[:,2])
                np.testing.assert_allclose(error,0,atol=2e-8,rtol=0)
                report['published_tum_max_error']=float(np.abs(error).max())
        # Independent start alignment is retained as a separate reporting policy.
        valid=seq.valid; anchor=int(np.flatnonzero(valid)[0])
        delta=seq.gt[anchor,2]-batch[anchor,2];c,s=np.cos(delta),np.sin(delta)
        independent=batch.copy()
        independent[:,:2]=(batch[:,:2]-batch[anchor,:2])@np.array([[c,s],[-s,c]])+seq.gt[anchor,:2]
        independent[:,2]=wrap(batch[:,2]+delta)
        report['independent_origin_metrics']=metrics(seq,independent)
    report['passed']=True
    return report


if __name__=='__main__':
    parser=argparse.ArgumentParser()
    parser.add_argument('--manifest',type=Path,required=True)
    parser.add_argument('--checkpoint',type=Path)
    parser.add_argument('--portable',type=Path)
    parser.add_argument('--label',help='override sampled stream to verify a new live run')
    parser.add_argument('--split',choices=['all','train','validation','test'],default='all')
    parser.add_argument('--output',type=Path,required=True)
    args=parser.parse_args();manifest=json.loads(args.manifest.read_text());reports=[]
    for source in manifest['sequences']:
        if args.split!='all' and source['sequence_id'] not in manifest[args.split]:continue
        row=source.copy();publication=None
        if args.label:
            directory=Path(row['cart']).parent
            row['sampled_stream']=str(directory/f'cartographer_noimu_sampled_stream_{args.label}.npz')
            publication=directory/f'cartographer_noimu_corrected_online_{args.label}.tum'
        reports.append(verify(row,args.checkpoint,publication,args.portable))
    args.output.parent.mkdir(parents=True,exist_ok=True)
    args.output.write_text(json.dumps(reports,ensure_ascii=False,indent=2,allow_nan=False)+'\n')
    print(json.dumps([{k:r[k] for k in ['sequence','samples','passed','training_feature_max_error']} for r in reports],indent=2))
